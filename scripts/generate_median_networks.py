"""Generate original finite-float median networks; no third-party code/data."""

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/craft_bridge/extensions/median/src/networks.rs"


def comparisons(length):
    pairs = []

    def merge(start, size, distance):
        stride = 2 * distance
        if stride < size:
            merge(start, size, stride)
            merge(start + distance, size, stride)
            for i in range(start + distance, start + size - distance, stride):
                pairs.append((i, i + distance))
        else:
            pairs.append((start, start + distance))

    def sort(start, size):
        if size > 1:
            sort(start, size // 2)
            sort(start + size // 2, size // 2)
            merge(start, size, 1)

    sort(0, 1 << (length - 1).bit_length())
    return [(a, b) for a, b in pairs if b < length]


def network(length, exact=False):
    pairs = comparisons(length)
    if exact:
        needed, kept = {length // 2}, []
        for a, b in reversed(pairs):
            if a in needed or b in needed:
                kept.append((a, b))
                needed.update((a, b))
        pairs = list(reversed(kept))
    name = ("exact" if exact else "network") + str(length)
    lines = ["#[inline(never)]", f"fn {name}(values: &[f32]) -> f32 {{"]
    for i in range(length):
        value = f"values[{i}]" if exact else ("values.first()" if i == 0 else f"values.get({i})") + ".copied().unwrap_or(f32::INFINITY)"
        lines.append(f"    let mut v{i} = {value};")
    for a, b in pairs:
        lines.append(f"    if v{a} > v{b} {{ std::mem::swap(&mut v{a}, &mut v{b}); }}")
    if exact:
        lines.append(f"    v{length // 2}")
    else:
        lines.append("    match values.len() / 2 {")
        lines.extend(f"        {i} => v{i}," for i in range(length // 2 + 1))
        lines.extend(["        _ => unreachable!(),", "    }"])
    return "\n".join([*lines, "}", ""])


if __name__ == "__main__":
    OUTPUT.write_text("// Generated by scripts/generate_median_networks.py; MIT original.\n"
                      "// Ascending Batcher odd-even mergesort; absent wires are positive infinity.\n"
                      "// Exact variants discard comparators that cannot feed the median wire.\n\n"
                      + "\n".join([network(n) for n in (15, 25, 36)]
                                   + [network(n, exact=True) for n in (33, 35)]))
    subprocess.run(["rustfmt", "+1.98.1", str(OUTPUT)], check=True, cwd=ROOT)
